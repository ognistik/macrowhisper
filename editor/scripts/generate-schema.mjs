import { readFile, writeFile, mkdir } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'

// A source projection, not a second hand-maintained configuration model.
const source = new URL('../../src/macrowhisper-schema.json', import.meta.url)
const destination = new URL('../src/generated/schema.ts', import.meta.url)
const schema = JSON.parse(await readFile(source, 'utf8'))

function properties(node) {
  const inherited = node.$ref
    ? properties(node.$ref.slice(2).split('/').reduce((value, key) => value[key], schema))
    : {}
  return Object.assign(inherited, ...(node.allOf ?? []).map(properties), node.properties ?? {})
}

const defaults = properties(schema.properties.defaults)
const inserts = properties(schema.definitions.insertAction)
const result = `// Generated by editor/scripts/generate-schema.mjs from src/macrowhisper-schema.json.
// Regenerate after schema edits; npm run schema:check can detect drift.
export const defaultsSchema = ${JSON.stringify(defaults, null, 2)} as const

export const insertSchema = ${JSON.stringify(inserts, null, 2)} as const

export type DefaultsSchemaKey = keyof typeof defaultsSchema
export type InsertSchemaKey = keyof typeof insertSchema

type Primitive<T> = T extends 'string' ? string
  : T extends 'number' | 'integer' ? number
  : T extends 'boolean' ? boolean
  : T extends 'null' ? null : never
type Value<T> = T extends { readonly type: infer U }
  ? U extends readonly unknown[] ? Primitive<U[number]> : Primitive<U> : never
export type SchemaDefaults = { [K in DefaultsSchemaKey]?: Value<(typeof defaultsSchema)[K]> }
export type SchemaInsert = { [K in InsertSchemaKey]?: Value<(typeof insertSchema)[K]> } & { action: string }
`

if (process.argv.includes('--check')) {
  const existing = await readFile(destination, 'utf8').catch(() => '')
  if (existing !== result) {
    console.error('Editor schema projection is stale. Run node editor/scripts/generate-schema.mjs.')
    process.exitCode = 1
  } else {
    console.log(`Schema projection matches production (${Object.keys(defaults).length} Defaults, ${Object.keys(inserts).length} Insert fields).`)
  }
} else {
  await mkdir(new URL('../src/generated/', import.meta.url), { recursive: true })
  await writeFile(destination, result)
  console.log(`Generated ${fileURLToPath(destination)}`)
}
